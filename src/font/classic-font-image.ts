import { MemoryImage } from "../memory/memory-image.ts";

/**
 * Expanded 80-byte representation of the original COSMAC VIP CHIP-8 font.
 *
 * @remarks
 * The image contains the 16 hexadecimal glyphs (`0` through `F`), with each
 * glyph occupying five consecutive bytes.
 *
 * The image deliberately contains no memory address. Its placement is a
 * machine-configuration decision and is supplied separately when loading it
 * into memory.
 */
export const CLASSIC_FONT_IMAGE = new MemoryImage(
  // prettier-ignore
  // deno-fmt-ignore
  [
  0xf0, 0x90, 0x90, 0x90, 0xf0, // 0
  0x60, 0x20, 0x20, 0x20, 0x70, // 1
  0xf0, 0x10, 0xf0, 0x80, 0xf0, // 2
  0xf0, 0x10, 0xf0, 0x10, 0xf0, // 3
  0xa0, 0xa0, 0xf0, 0x20, 0x20, // 4
  0xf0, 0x80, 0xf0, 0x10, 0xf0, // 5
  0xf0, 0x80, 0xf0, 0x90, 0xf0, // 6
  0xf0, 0x10, 0x10, 0x10, 0x10, // 7
  0xf0, 0x90, 0xf0, 0x90, 0xf0, // 8
  0xf0, 0x90, 0xf0, 0x10, 0xf0, // 9
  0xf0, 0x90, 0xf0, 0x90, 0x90, // A
  0xf0, 0x50, 0x70, 0x50, 0xf0, // B
  0xf0, 0x80, 0x80, 0x80, 0xf0, // C
  0xf0, 0x50, 0x50, 0x50, 0xf0, // D
  0xf0, 0x80, 0xf0, 0x80, 0xf0, // E
  0xf0, 0x80, 0xf0, 0x80, 0x80, // F
],
);
